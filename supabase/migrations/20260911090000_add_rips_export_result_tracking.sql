-- Odentia Core — RIPS #5B: pilot-validation traceability for a generated
-- RIPS sin factura export.
--
-- This is explicitly NOT a SISPRO/MUV integration (see RIPS #6A — PASS
-- WITH ISSUES, no automatic connection exists or is planned here). Every
-- column added below captures either (a) a content fingerprint of a file
-- Odentia itself generated, or (b) a result a human typed in AFTER
-- performing the official manual upload themselves. Odentia never
-- transmits anything and never infers a MUV outcome from its own internal
-- validation passing.
--
-- content_hash: SHA-256 (hex, lowercase, 64 chars) of the EXACT UTF-8
-- serialized JSON string handed to the browser for download — computed
-- server-side in export-actions.ts from the same string variable that is
-- returned for download, never recomputed from a re-serialized object (see
-- export-hash.ts). This is what lets a later manual MUV result be tied
-- unambiguously to the file that was actually uploaded, without Odentia
-- ever storing the file's own PII-bearing content a second time.
--
-- result_status starts at 'generated' for every row (this task's own
-- Section 9 — "no permitir falsos positivos") and can move to 'accepted'
-- or 'rejected' exactly once, via record_rips_export_result() below —
-- never editable afterwards (Section 20's simplest option: no edit RPC in
-- this MVP). A correction to a mistaken entry is a deliberate future
-- admin action, not a CRUD surface.
alter table public.rips_export_log
  add column content_hash text,
  add column result_status text not null default 'generated',
  add column muv_proceso_id text,
  add column muv_cuv text,
  add column muv_radicacion_at timestamptz,
  add column muv_result_notes text,
  add column result_recorded_at timestamptz,
  add column result_recorded_by uuid references public.profiles (id) on delete set null;

alter table public.rips_export_log
  add constraint rips_export_log_content_hash_format check (content_hash is null or content_hash ~ '^[0-9a-f]{64}$');

alter table public.rips_export_log
  add constraint rips_export_log_result_status_check check (result_status in ('generated', 'accepted', 'rejected'));

-- A CUV is the Ministry's own proof of acceptance — an 'accepted' row
-- without one would just be an unverified claim (Section 11: never
-- inferred/generated by Odentia, only ever typed in from a real MUV
-- result). A 'rejected' row without any note would carry no actionable
-- information for improving the generator (Section 12's whole point).
alter table public.rips_export_log
  add constraint rips_export_log_accepted_requires_cuv check (result_status <> 'accepted' or muv_cuv is not null);

alter table public.rips_export_log
  add constraint rips_export_log_rejected_requires_notes check (result_status <> 'rejected' or muv_result_notes is not null);

-- Tightened from RIPS #5's original rips_export_log_select_member (any
-- clinic member). This task's own Section 17 is explicit: RIPS export
-- history/results are clinic_admin-only, never assistant/dentist —
-- unlike encounter_diagnoses/encounter_services, which staff genuinely
-- need to read for clinical care. The route (/rips) and every server
-- action already independently re-check role === 'clinic_admin'
-- (export-actions.ts's own requireClinicAdminContext) — this brings RLS
-- itself in line rather than relying on the app layer alone.
drop policy rips_export_log_select_member on public.rips_export_log;

create policy rips_export_log_select_admin
  on public.rips_export_log for select
  to authenticated
  using (public.has_clinic_role(clinic_id, array['clinic_admin']::public.membership_role[]));

-- Replaces RIPS #5's log_rips_export — same body/authorization shape,
-- plus the required content_hash. Dropped and recreated (not CREATE OR
-- REPLACE) because the parameter list itself changes; the original
-- migration file is left untouched (CLAUDE.md's own "never edit an
-- applied migration").
drop function public.log_rips_export(integer, integer, integer, integer, integer);

create function public.log_rips_export(
  p_period_year integer,
  p_period_month integer,
  p_patient_count integer,
  p_consultation_count integer,
  p_procedure_count integer,
  p_content_hash text
)
returns public.rips_export_log
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_clinic_id uuid;
  v_result public.rips_export_log;
begin
  select clinic_id into v_clinic_id
  from public.clinic_memberships
  where profile_id = auth.uid() and role = 'clinic_admin' and status = 'active'
  limit 1;

  if v_clinic_id is null then
    raise exception 'not authorized to generate a RIPS export for this clinic' using errcode = '42501';
  end if;

  if p_content_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'content_hash must be a 64-character lowercase hex SHA-256 digest' using errcode = '22023';
  end if;

  insert into public.rips_export_log (
    clinic_id, period_year, period_month, generated_by, patient_count, consultation_count, procedure_count, content_hash
  )
  values (
    v_clinic_id, p_period_year, p_period_month, auth.uid(), p_patient_count, p_consultation_count, p_procedure_count, p_content_hash
  )
  returning * into v_result;

  return v_result;
end;
$$;

revoke execute on function public.log_rips_export(integer, integer, integer, integer, integer, text) from public;
grant execute on function public.log_rips_export(integer, integer, integer, integer, integer, text) to authenticated;

-- The ONLY write path for a manual MUV result (Section 17 — "no writes
-- directos authenticated"). Enforces, server-side, everything the app
-- layer also checks: clinic_admin only, the export must belong to the
-- caller's own clinic, a result may be recorded exactly once
-- (result_status must still be 'generated'), and the minimal evidence
-- each outcome requires (Section 20/9 — no silent overwrite, no
-- unverified 'accepted').
--
-- Concurrency: the initial SELECT below takes `FOR UPDATE` on the target
-- row, so two concurrent calls against the SAME export can never both
-- read result_status = 'generated'. The first caller to reach the SELECT
-- acquires the row lock and proceeds (validate → UPDATE → implicit
-- commit at the end of this single-statement RPC call, which releases
-- the lock). A second, concurrent call blocks on its own `FOR UPDATE`
-- until that commit happens, then reads the row AS IT NOW STANDS —
-- already 'accepted'/'rejected' — and is correctly rejected by the
-- existing "result already recorded" check below (errcode 55000). No new
-- error path, no isolation-level change: plain READ COMMITTED plus a row
-- lock is sufficient here because every write to this row goes through
-- this one function.
create function public.record_rips_export_result(
  p_export_id uuid,
  p_result_status text,
  p_muv_proceso_id text default null,
  p_muv_cuv text default null,
  p_muv_radicacion_at timestamptz default null,
  p_muv_result_notes text default null
)
returns public.rips_export_log
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_current public.rips_export_log;
  v_result public.rips_export_log;
begin
  if p_result_status not in ('accepted', 'rejected') then
    raise exception 'invalid result status: %', p_result_status using errcode = '22023';
  end if;

  -- FOR UPDATE closes the check-then-act race: see this function's own
  -- comment above.
  select * into v_current from public.rips_export_log where id = p_export_id for update;
  if v_current.id is null then
    raise exception 'export not found' using errcode = 'P0002';
  end if;

  -- Reuses has_clinic_role() (foundation RLS migration) rather than a new
  -- predicate — same helper the tightened SELECT policy above uses.
  if not public.has_clinic_role(v_current.clinic_id, array['clinic_admin']::public.membership_role[]) then
    raise exception 'not authorized to record a result for this export' using errcode = '42501';
  end if;

  if v_current.result_status <> 'generated' then
    raise exception 'a result was already recorded for this export and cannot be changed' using errcode = '55000';
  end if;

  if p_result_status = 'accepted' and coalesce(btrim(p_muv_cuv), '') = '' then
    raise exception 'CUV is required to record an accepted MUV result' using errcode = '23514';
  end if;

  if p_result_status = 'rejected' and coalesce(btrim(p_muv_result_notes), '') = '' then
    raise exception 'a summary is required to record a rejected MUV result' using errcode = '23514';
  end if;

  update public.rips_export_log
  set
    result_status = p_result_status,
    muv_proceso_id = nullif(btrim(p_muv_proceso_id), ''),
    muv_cuv = nullif(btrim(p_muv_cuv), ''),
    muv_radicacion_at = p_muv_radicacion_at,
    muv_result_notes = nullif(btrim(p_muv_result_notes), ''),
    result_recorded_at = now(),
    result_recorded_by = auth.uid()
  where id = p_export_id
  returning * into v_result;

  return v_result;
end;
$$;

revoke execute on function public.record_rips_export_result(uuid, text, text, text, timestamptz, text) from public;
grant execute on function public.record_rips_export_result(uuid, text, text, text, timestamptz, text) to authenticated;
